    private void menuProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuProcessActionPerformed
        price = txtPrice.getText();
        number = txtNumber.getText();
       //get the string name of selected location from cmb
        movie = (String) cmbMovie.getSelectedItem();

       MovieTickets mt = new MovieTickets();
       MovieTicketData mtd = new MovieTicketData(movie, number, price);

       if (mt.ValidateData(mtd)) {
       // if the data is valid
       txtOutput.setText("MOVIE NAME: " + movie);
       txtOutput.append(String.format("\nMOVIE TICKET PRICE: R %.1f", Double.parseDouble(price)));
       txtOutput.append("\nNUMBER OF TICKETS: " + number);
       txtOutput.append(String.format("\nTOTAL TICKET PRICE: R %.1f", mt.CalculateTotalTicketPrice(Integer.parseInt(number) , Double.parseDouble(price))));
      
       //save to text file
        try (FileWriter writer = new FileWriter("report.txt", true)) {
            writer.write("\nMOVIE TICKET REPORT");
            writer.write("\n************************");
            writer.write("\nMOVIE NAME: " + movie);
            writer.write(String.format("\nMOVIE TICKET PRICE: R %.1f", Double.parseDouble(price)));
            writer.write("\nNUMBER OF TICKETS: " + number);
            writer.write(String.format("\nTOTAL TICKET PRICE: R %.1f", mt.CalculateTotalTicketPrice(Integer.parseInt(number) , Double.parseDouble(price))));
            writer.write("\n************************");
            txtOutput.append(" ");
            txtOutput.append("\nData saved successfully.");
        } catch (IOException e) {
            System.out.println("An error occurred while saving.");
            e.printStackTrace();
        }
       
       } else {
           txtOutput.setText("Please enter valid data.");
       }
       
       
      
    }//GEN-LAST:event_menuProcessActionPerformed

